"""Draw functional panels from fresh fits and an optional local connectome summary."""
from __future__ import annotations
import argparse
from pathlib import Path
import matplotlib
matplotlib.use('Agg')
import matplotlib.pyplot as plt
import numpy as np
import pandas as pd
from scipy.stats import linregress
from .paths import PROJECT_ROOT
from .reproduction import ANALYSES

STYLES = {
    'Power_law': ('#2ca02c', 'P'), 'Exponential': ('#d62728', 'E'),
    'Truncated_Power_law': ('#ff7f0e', 'T'), 'Log_normal': ('#1f77b4', 'L'),
    'Stretched_Exponential': ('#9467bd', 'S'),
}


def save_figure(fig, stem):
    for suffix in ['png', 'pdf', 'svg']:
        fig.savefig(stem.with_suffix('.' + suffix), dpi=300, bbox_inches='tight')
    plt.close(fig)


def functional_figure(name, output, fits_dir):
    config = ANALYSES[name]
    data = pd.read_csv(PROJECT_ROOT / f'data/functional/{name}.csv.gz')
    columns = config['continuous'] + [config['response']]
    corr = data[columns].corr()
    fit_dir = fits_dir / name
    metrics = pd.read_csv(fit_dir / 'model_performance.csv').sort_values('quantile')
    interval_path = fit_dir / 'distribution_effect_confidence_intervals.csv'
    has_intervals = interval_path.exists()
    effects = (pd.read_csv(interval_path) if has_intervals else
               pd.read_csv(fit_dir / 'distribution_effects.csv').rename(columns={'effect': 'mean_effect'}))
    quantiles = metrics['quantile'].tolist()
    expected = {(q, family) for q in quantiles for family in STYLES}
    actual = set(zip(effects['quantile'], effects['distribution_type']))
    if len(expected) != len(effects) or actual != expected:
        raise ValueError(f'Family predictions and diagnostics do not match in {fit_dir}')
    fig = plt.figure(figsize=(8, 3.7), layout='constrained')
    gs = fig.add_gridspec(2, 2, width_ratios=[1, 1.25], height_ratios=[1, 3])
    ax = fig.add_subplot(gs[:, 0])
    arr = corr.to_numpy(); image = ax.imshow(arr, vmin=-1, vmax=1, cmap='RdBu_r')
    labels = [c.replace('spatial_temporal_sum_factor', 'factor').replace('initial_avg_degree', 'avg_degree') for c in columns]
    ax.set_xticks(range(len(labels)), labels, rotation=45, ha='right')
    ax.set_yticks(range(len(labels)), labels)
    for i in range(len(labels)):
        for j in range(len(labels)):
            ax.text(j, i, f'{arr[i,j]:.2f}', ha='center', va='center', fontsize=6,
                    color='white' if abs(arr[i,j]) > .65 else '#222222')
    fig.colorbar(image, ax=ax, shrink=.65, label='Pearson r')
    ax.set_title('a  ' + name.capitalize(), loc='left', fontweight='bold')
    top = fig.add_subplot(gs[0, 1]); twin = top.twinx(); x = np.arange(len(quantiles))
    top.plot(x, metrics.r2, 'o-', color='#1f77b4', ms=3); top.set_ylabel('R²', color='#1f77b4')
    twin.plot(x, metrics.mse, 's--', color='#d62728', ms=3); twin.set_ylabel('MSE', color='#d62728')
    prediction_label = 'bootstrap means' if has_intervals else 'single-fit predictions'
    top.set_xticks([]); top.set_title(f'b  Model diagnostics and {prediction_label}', loc='left', fontweight='bold')
    bottom = fig.add_subplot(gs[1, 1])
    for family, (color, label) in STYLES.items():
        part = effects[effects.distribution_type.eq(family)].sort_values('quantile')
        bottom.plot(x, part.mean_effect, 'o-', color=color, ms=3, lw=1.1, label=label)
        if has_intervals:
            bottom.fill_between(x, part.ci_lower, part.ci_upper, color=color, alpha=.13, lw=0)
    bottom.set_xticks(x, [f'{q:g}' for q in quantiles])
    bottom.set_xlabel('Weighting index τ'); bottom.set_ylabel('Family prediction')
    bottom.legend(ncol=5, frameon=False, loc='upper center', bbox_to_anchor=(.5, -.2))
    corr.to_csv(output / f'{name}_correlations.csv')
    save_figure(fig, output / f'{name}_functional_panels')


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--outdir', type=Path, default=PROJECT_ROOT / 'result/figures')
    parser.add_argument('--fits-dir', type=Path, default=PROJECT_ROOT / 'result/statistical_analysis')
    parser.add_argument('--analysis', choices=[*ANALYSES, 'all'], default='all')
    parser.add_argument('--empirical-summary', type=Path,
                        help='optional connectome_dataset_summary.csv generated by the summary command')
    args = parser.parse_args()
    selected = list(ANALYSES) if args.analysis == 'all' else [args.analysis]
    for name in selected:
        for filename in ['model_performance.csv', 'distribution_effects.csv']:
            if not (args.fits_dir / name / filename).is_file():
                parser.error(f'Missing {args.fits_dir / name / filename}; run "python reproduce.py fit {name}" first')
    if args.empirical_summary is not None and not args.empirical_summary.is_file():
        parser.error(f'Missing empirical summary: {args.empirical_summary}; run "python reproduce.py summary" first')
    args.outdir.mkdir(parents=True, exist_ok=True)
    plt.rcParams.update({'font.family': 'DejaVu Sans', 'font.size': 8, 'axes.labelsize': 8,
                         'xtick.labelsize': 7, 'ytick.labelsize': 7, 'axes.spines.top': False,
                         'axes.spines.right': False, 'pdf.fonttype': 42, 'svg.fonttype': 'none'})
    for name in selected:
        functional_figure(name, args.outdir, args.fits_dir)
    count = len(selected)
    if args.empirical_summary is not None:
        table = pd.read_csv(args.empirical_summary)
        fit = linregress(np.log(table.nodes), np.log(table.edges))
        fig, ax = plt.subplots(figsize=(4.5, 3))
        ax.scatter(table.nodes, table.edges, s=table.average_total_degree * 3, alpha=.7, edgecolor='white', lw=.4)
        x = np.geomspace(table.nodes.min(), table.nodes.max(), 100)
        ax.plot(x, np.exp(fit.intercept) * x ** fit.slope, color='#333333', lw=1)
        ax.set(xscale='log', yscale='log', xlabel='Neurons N', ylabel='Directed edges E')
        ax.text(.05, .9, f'E = {np.exp(fit.intercept):.2f} N^{fit.slope:.2f}\nR² = {fit.rvalue**2:.3f}', transform=ax.transAxes)
        save_figure(fig, args.outdir / 'network_size_relationship')
        count += 1
    print(f'Wrote {count} figures in PNG, PDF and SVG to {args.outdir}')


if __name__ == '__main__':
    main()
